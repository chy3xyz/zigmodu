#!/usr/bin/env node
// zsaas business-module generator (frontend) — data-driven SolidStart admin
// page for a zigmodu backend, built on the shared scaffolding:
//   src/libs/apiClient.ts          typed zigmodu envelope client (commit once)
//   src/components/data/DataTable.tsx  +  EntityForm.tsx   (commit once)
//   src/models/<P>.ts              entity type + field schema  (generated)
//   src/routes/dashboard/<name>/index.tsx  CRUD page         (generated)
// The backend module is generated separately with `zmodu saas <model.json>`
// from the SAME model file.
//
// Usage:
//   node scripts/gen-business.mjs <model.json> <target-project-dir>
//
// Model shape:
//   { "entities": [ {
//       "name": "orders",            // backend route + module (plural)
//       "label": "Orders",
//       "description": "...",
//       "fields": [ { "name": "customer", "type": "string", "required": true,
//                     "label": "Customer", "options": [{"value","label"}] } ]
//   } ] }
// Field types: string | text | number | boolean | select (string + options)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MODEL_PATH = process.argv[2];
const TARGET = process.argv[3];
if (!MODEL_PATH || !TARGET) {
  console.error('usage: node scripts/gen-business.mjs <model.json> <target-project-dir>');
  process.exit(2);
}

const model = JSON.parse(fs.readFileSync(MODEL_PATH, 'utf8'));

function pascal(name) {
  return name.split(/[-_]/).map(s => s[0].toUpperCase() + s.slice(1)).join('');
}

function tsType(t) {
  return t === 'number' ? 'number' : t === 'boolean' ? 'boolean' : 'string';
}

function formType(f) {
  if (f.options) return 'select';
  if (f.type === 'text') return 'textarea';
  if (f.type === 'boolean') return 'select';
  if (f.type === 'number') return 'number';
  return 'text';
}

// Entity model file: TS type + shared field schema (used by DataTable and
// EntityForm so a generated CRUD screen stays data-driven).
function modelTpl(e) {
  const P = pascal(e.name);
  const typeFields = e.fields.map(f => `  ${f.name}${f.required ? '' : '?'}: ${tsType(f.type)};`).join('\n');
  const fieldDefs = e.fields.map(f => {
    const parts = [
      `  { name: '${f.name}', label: '${f.label ?? f.name}', type: '${formType(f)}'`,
    ];
    if (f.required) parts.push("required: true");
    if (f.type === 'boolean') {
      parts.push("options: [{ value: 'true', label: 'True' }, { value: 'false', label: 'False' }]");
    } else if (f.options) {
      parts.push(`options: ${JSON.stringify(f.options.map(o => ({ value: String(o.value), label: o.label ?? String(o.value) })))}`);
    }
    if (f.placeholder) parts.push(`placeholder: '${f.placeholder}'`);
    return `${parts.join(', ')}}`;
  }).join(',\n');
  return `// Generated by zsaas gen-business — ${e.name} entity + UI field schema.
// Shared by DataTable / EntityForm so the CRUD screen is data-driven.

export type ${P} = {
  id: number;
  org_id: number;
${typeFields}
  created_at: number;
  updated_at: number;
};

export type ${P}Field = {
  name: string;
  label: string;
  type: 'text' | 'number' | 'textarea' | 'select';
  required?: boolean;
  options?: { value: string; label: string }[];
  placeholder?: string;
};

export const ${P}Fields: ${P}Field[] = [
${fieldDefs},
];
`;
}

// Single data-driven CRUD page: list (DataTable) + create/edit (EntityForm)
// against the zigmodu backend via the shared apiClient.
function pageTpl(e) {
  const P = pascal(e.name);
  const LP = e.name;
  const title = e.label ?? P;
  const hasSelect = e.fields.some(f => formType(f) === 'select');
  const badgeImport = hasSelect
    ? `import { Badge } from '@/components/ui/badge';\n`
    : '';
  const statusTone = hasSelect
    ? `const tone: Record<string, string> = {\n  pending: 'bg-yellow-100 text-yellow-800',\n  paid: 'bg-green-100 text-green-800',\n  cancelled: 'bg-red-100 text-red-800',\n};\nconst toneFor = (v: string) => tone[v] ?? 'bg-muted text-muted-foreground';\n`
    : '';
  const renderers = e.fields.map(f => {
    if (formType(f) === 'select') {
      return `  { key: '${f.name}', header: '${f.label ?? f.name}', render: (r) => <Badge class={toneFor(String(r.${f.name}))}>{String(r.${f.name})}</Badge> },`;
    }
    return `  { key: '${f.name}', header: '${f.label ?? f.name}'${f.type === 'number' ? `, render: (r) => String(r.${f.name})` : ''} },`;
  }).join('\n');
  const bodyFields = e.fields.map(f => {
    const raw = `raw.${f.name}`;
    if (f.type === 'number') return `      ${f.name}: raw.${f.name} === '' ? undefined : Number(raw.${f.name}),`;
    if (f.type === 'boolean') return `      ${f.name}: raw.${f.name} === 'true',`;
    return `      ${f.name}: raw.${f.name} ?? '',`;
  }).join('\n');

  return `// Generated by zsaas gen-business — ${e.name} CRUD page
import { Title } from '@solidjs/meta';
import { createEffect, createSignal, Show } from 'solid-js';
import { DataTable, type ColumnDef } from '@/components/data/DataTable';
import { EntityForm } from '@/components/data/EntityForm';
${badgeImport}import { Button } from '@/components/ui/button';
import { createApiClient, login, type ApiClient } from '@/libs/apiClient';
import { ${P}Fields, type ${P} } from '@/models/${P}';

const API_URL = import.meta.env.VITE_API_URL ?? 'http://127.0.0.1:18080/api/v1';

${statusTone}
const columns: ColumnDef<${P}>[] = [
  { key: 'id', header: 'ID' },
${renderers}
  { key: 'updated_at', header: 'Updated', render: (r) => new Date(r.updated_at * 1000).toLocaleString() },
];

export default function ${P}Page() {
  const [client, setClient] = createSignal<ApiClient | null>(null);
  const [rows, setRows] = createSignal<${P}[]>([]);
  const [total, setTotal] = createSignal(0);
  const [page, setPage] = createSignal(1);
  const [loading, setLoading] = createSignal(true);
  const [error, setError] = createSignal<string | null>(null);
  const [editing, setEditing] = createSignal<${P} | null>(null);
  const [showCreate, setShowCreate] = createSignal(false);

  async function refresh(c: ApiClient) {
    setLoading(true);
    try {
      const result = await c.list<${P}>('${LP}', { page: page(), page_size: 20 });
      setRows(result.items);
      setTotal(result.total);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load ${LP}');
    } finally {
      setLoading(false);
    }
  }

  async function init() {
    try {
      const token = await login(API_URL);
      const c = createApiClient(API_URL, () => token);
      setClient(c);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Backend unavailable');
    }
  }

  // Boot: login once, then refresh on every client/page change (page() is
  // read synchronously inside refresh, so Solid tracks it for re-fetch).
  createEffect(() => {
    if (!client()) {
      void init();
      return;
    }
    void refresh(client()!);
  });

  async function submitForm(raw: Record<string, string>) {
    const c = client();
    if (!c) return;
    const body = {
${bodyFields}
    };
    if (editing()) {
      await c.update('${LP}', editing()!.id, body);
    } else {
      await c.create('${LP}', body);
    }
    setEditing(null);
    setShowCreate(false);
    await refresh(c);
  }

  async function remove(row: ${P}) {
    const c = client();
    if (!c) return;
    if (!window.confirm(\`Delete ${LP} #\${row.id}?\`)) return;
    await c.remove('${LP}', row.id);
    await refresh(c);
  }

  return (
    <>
      <Title>${title}</Title>
      <div class="mb-6 flex items-center justify-between">
        <div>
          <h1 class="text-2xl font-semibold">${title}</h1>
          <p class="text-sm text-muted-foreground">${e.description ?? 'zigmodu autoCrud + DataTable / EntityForm'}</p>
        </div>
        <Button onClick={() => { setShowCreate(true); setEditing(null); }}>New ${P}</Button>
      </div>
      <Show when={error()}>
        <p class="mb-4 rounded-md bg-destructive/10 px-3 py-2 text-sm text-destructive">{error()}</p>
      </Show>
      <Show when={showCreate() || editing()}>
        <div class="mb-6 rounded-lg border bg-card p-5">
          <h2 class="mb-4 text-lg font-semibold">{editing() ? \`Edit ${LP} #\${editing()!.id}\` : 'New ${LP}'}</h2>
          <EntityForm
            fields={${P}Fields}
            initial={editing() ?? undefined}
            submitLabel={editing() ? 'Save' : 'Create'}
            onSubmit={submitForm}
            onCancel={() => { setShowCreate(false); setEditing(null); }}
          />
        </div>
      </Show>
      <DataTable
        columns={columns}
        rows={rows()}
        total={total()}
        page={page()}
        pageSize={20}
        loading={loading()}
        rowKey={(r) => r.id}
        onEdit={setEditing}
        onDelete={remove}
        emptyText="No ${LP} yet"
        onPageChange={(p) => setPage(p)}
      />
    </>
  );
}
`;
}

function generateEntity(e, out) {
  const dir = path.join(out, 'src');
  const P = pascal(e.name);

  // 1. entity model + field schema
  const modelDir = path.join(dir, 'models');
  fs.mkdirSync(modelDir, { recursive: true });
  fs.writeFileSync(path.join(modelDir, `${P}.ts`), modelTpl(e));

  // 2. data-driven dashboard route
  const routeDir = path.join(dir, 'routes', 'dashboard', e.name);
  fs.mkdirSync(routeDir, { recursive: true });
  fs.writeFileSync(path.join(routeDir, 'index.tsx'), pageTpl(e));

  console.log(`[zsaas] generated ${e.name} -> ${dir}`);
}

for (const e of model.entities) {
  generateEntity(e, TARGET);
}
console.log('[zsaas] done');
