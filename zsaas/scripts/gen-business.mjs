#!/usr/bin/env node
// zsaas business-module generator (frontend) — SolidStart admin pages + a
// typed REST client for a zigmodu backend. The backend module is generated
// separately with `zmodu saas <model.json>` from the SAME model file.
//
// Usage:
//   node scripts/gen-business.mjs <model.json> <target-project-dir>
//
// Model shape:
//   { "entities": [ {
//       "name": "orders",            // backend route + module (plural)
//       "label": "Orders",
//       "description": "...",
//       "writeRole": "admin",        // member | admin
//       "fields": [ { "name": "customer", "type": "string", "required": true } ]
//   } ] }
// Field types: string | text | number | boolean | date

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MODEL_PATH = process.argv[2];
const TARGET = process.argv[3];
if (!MODEL_PATH || !TARGET) {
  console.error('usage: node scripts/gen-business.mjs <model.json> <target-project-dir>');
  process.exit(2);
}

const model = JSON.parse(fs.readFileSync(MODEL_PATH, 'utf8'));

function pascal(name) {
  return name.split(/[-_]/).map(s => s[0].toUpperCase() + s.slice(1)).join('');
}

function pluralP(p) {
  return p.endsWith('s') ? p : p + 's';
}

function tsType(t) {
  return t === 'number' ? 'number' : t === 'boolean' ? 'boolean' : 'string';
}

const ZMODU_API_TS = `// Generated by zsaas gen-business — zigmodu REST bridge (server-side)
// The SolidStart server proxies business CRUD to the zigmodu backend.
// Production: set ZMODU_API_TOKEN from an authenticated session (exchange the
// SolidStart cookie for a zigmodu JWT); dev uses the env var.
const BASE = process.env.PUBLIC_ZMODU_API_URL ?? 'http://127.0.0.1:8080';
const TOKEN = process.env.ZMODU_API_TOKEN ?? '';

export async function zmoduFetch<T = unknown>(path: string, init?: RequestInit): Promise<T> {
  const res = await fetch(\`\${BASE}/api/v1\${path}\`, {
    ...init,
    headers: {
      'Content-Type': 'application/json',
      ...(TOKEN ? { Authorization: \`Bearer \${TOKEN}\` } : {}),
      ...init?.headers,
    },
  });
  if (!res.ok) throw new Error(\`zmodu \${path}: HTTP \${res.status}\`);
  const json = (await res.json()) as { code?: number; msg?: string; items?: T; data?: T };
  if (json.code !== undefined && json.code !== 0) throw new Error(json.msg ?? 'zmodu error');
  return (json.items ?? json.data ?? json) as T;
}
`;

function actionsTpl(e) {
  const P = pascal(e.name);
  const LP = pluralP(P);
  const writeRole = e.writeRole === 'member' ? 'ORG_ROLE.MEMBER' : 'ORG_ROLE.ADMIN';
  const typeFields = e.fields.map(f => `  ${f.name}${f.required ? '' : '?'}: ${tsType(f.type)};`).join('\n');
  const bodyFields = e.fields.map(f => {
    if (f.type === 'number') {
      return `  const ${f.name} = formData.get('${f.name}'); data.${f.name} = ${f.name} !== null && ${f.name} !== '' ? Number(${f.name}) : undefined;`;
    }
    if (f.type === 'boolean') {
      return `  data.${f.name} = formData.get('${f.name}') === 'on';`;
    }
    return `  const ${f.name} = formData.get('${f.name}'); if (typeof ${f.name} === 'string' && ${f.name} !== '') data.${f.name} = ${f.name};`;
  }).join('\n');
  return `// Generated by zsaas gen-business — ${e.name} server actions
import { action, query } from '@solidjs/router';
import { zmoduFetch } from '@/libs/zmoduApi';
import { guardForm } from '@/libs/csrf';
import { requireOrgMember } from '@/libs/rbac';
import { ORG_ROLE } from '@/types/Auth';

export type ${P} = {
  id: number;
  orgId: number;
${typeFields}
  createdAt: number;
  updatedAt: number;
};

export const query${LP} = query(async () => {
  'use server';
  await requireOrgMember(ORG_ROLE.MEMBER);
  return zmoduFetch<${P}[]>('/${e.name}?page=1&size=50');
}, '${e.name}.list');

export const query${P}ById = query(async (id: number) => {
  'use server';
  await requireOrgMember(ORG_ROLE.MEMBER);
  return zmoduFetch<${P} | null>('/${e.name}/' + id);
}, '${e.name}.get');

export const formCreate${P} = action(async (formData: FormData) => {
  'use server';
  await guardForm(formData);
  await requireOrgMember(${writeRole});
  const data: Record<string, unknown> = {};
${bodyFields}
  await zmoduFetch('/${e.name}', { method: 'POST', body: JSON.stringify(data) });
});

export const formUpdate${P} = action(async (formData: FormData) => {
  'use server';
  await guardForm(formData);
  await requireOrgMember(${writeRole});
  const id = Number(formData.get('id'));
  if (!Number.isFinite(id)) throw new Error('Missing id');
  const data: Record<string, unknown> = {};
${bodyFields}
  await zmoduFetch('/${e.name}/' + id, { method: 'PUT', body: JSON.stringify(data) });
});

export const formDelete${P} = action(async (formData: FormData) => {
  'use server';
  await guardForm(formData);
  await requireOrgMember(${writeRole});
  const id = Number(formData.get('id'));
  if (!Number.isFinite(id)) throw new Error('Missing id');
  await zmoduFetch('/${e.name}/' + id, { method: 'DELETE' });
});
`;
}

function listPageTpl(e) {
  const P = pascal(e.name);
  const LP = pluralP(P);
  const cols = e.fields.map(f => `            <td class="py-2 pr-4 text-sm">{(r).${f.name} ?? ''}</td>`).join('\n');
  return `// Generated by zsaas gen-business — ${e.name} list page
import { createAsync } from '@solidjs/router';
import { For, Show } from 'solid-js';
import { query${LP} } from '@/business/${e.name}';
import { formDelete${P} } from '@/business/${e.name}';
import { CsrfField } from '@/components/CsrfField';
import { buttonVariants } from '@/components/ui/buttonVariants';
import { TitleBar } from '@/features/dashboard/shared';
import { useTranslations } from '@/libs/I18nContext';

export default function ${P}ListPage() {
  const t = useTranslations();
  const items = createAsync(() => query${LP}());

  return (
    <>
      <TitleBar title={t('${P}Page.title_bar')} description={t('${P}Page.title_bar_description')} />
      <div class="rounded-xl border bg-card p-6">
        <div class="mb-4 flex items-center justify-between">
          <h2 class="font-semibold">{t('${P}Page.list')}</h2>
          <a href="./new" class={buttonVariants({ size: 'sm' })}>{t('${P}Page.create')}</a>
        </div>
        <Show when={(items()?.length ?? 0) === 0}>
          <p class="text-sm text-muted-foreground">{t('${P}Page.empty')}</p>
        </Show>
        <table class="w-full text-left">
          <thead>
            <tr class="border-b text-sm text-muted-foreground">
${e.fields.map(f => `              <th class="py-2 pr-4 font-medium">${f.name}</th>`).join('\n')}
              <th class="py-2 pr-4 font-medium"></th>
            </tr>
          </thead>
          <tbody>
            <For each={items()}>
              {(r) => (
                <tr class="border-b last:border-0">
${cols}
                  <td class="py-2 text-right">
                    <a href={String(r.id)} class={buttonVariants({ variant: 'outline', size: 'sm' })}>{t('${P}Page.edit')}</a>
                    <form action={formDelete${P}} method="post" class="inline">
                      <CsrfField />
                      <input type="hidden" name="id" value={r.id} />
                      <button type="submit" class={buttonVariants({ variant: 'outline', size: 'sm' })}>{t('${P}Page.delete')}</button>
                    </form>
                  </td>
                </tr>
              )}
            </For>
          </tbody>
        </table>
      </div>
    </>
  );
}
`;
}

function formPageTpl(e, mode) {
  const P = pascal(e.name);
  const isEdit = mode === 'edit';
  const actionName = isEdit ? `formUpdate${P}` : `formCreate${P}`;
  const inputs = e.fields.map(f => {
    const label = `${P}Page.f_${f.name}`;
    const required = f.required ? ' required' : '';
    const prefill = isEdit
      ? f.type === 'boolean'
        ? ` checked={item()!.${f.name}}`
        : ` value={item()!.${f.name}}`
      : '';
    let input = '';
    if (f.type === 'boolean') {
      input = `          <input type="checkbox" name="${f.name}" class="mt-1"${required}${prefill} />`;
    } else if (f.type === 'number') {
      input = `          <input type="number" step="any" name="${f.name}" class="w-full rounded-md border bg-background px-3 py-2 text-sm"${required}${prefill} />`;
    } else {
      input = `          <input name="${f.name}" class="w-full rounded-md border bg-background px-3 py-2 text-sm"${required}${prefill} />`;
    }
    return `        <label class="block text-sm">
          <span class="mb-1 block font-medium">{t('${label}')}</span>
${input}
        </label>`;
  }).join('\n');
  const imports = isEdit
    ? `import { createAsync, useSubmission } from '@solidjs/router';\nimport { query${P}ById } from '@/business/${e.name}';\nimport { formUpdate${P} } from '@/business/${e.name}';`
    : `import { useSubmission } from '@solidjs/router';\nimport { formCreate${P} } from '@/business/${e.name}';`;
  return `// Generated by zsaas gen-business — ${e.name} ${isEdit ? 'edit' : 'new'} page
${imports}
import { Show } from 'solid-js';
import { CsrfField } from '@/components/CsrfField';
import { buttonVariants } from '@/components/ui/buttonVariants';
import { TitleBar } from '@/features/dashboard/shared';
import { useTranslations } from '@/libs/I18nContext';

export default function ${P}${isEdit ? 'Edit' : 'New'}Page(${isEdit ? 'props: { params: { id: string } }' : ''}) {
  const t = useTranslations();
  ${isEdit ? `const item = createAsync(() => query${P}ById(Number(props.params.id)));` : ''}
  const submission = useSubmission(${actionName});

  return (
    <>
      <TitleBar title={t('${P}Page.${isEdit ? 'edit_title' : 'create_title'}')} />
      <Show when={${isEdit ? 'item()' : 'true'}}>
        <form action={${actionName}} method="post" class="max-w-md space-y-4 rounded-xl border bg-card p-6">
          <CsrfField />
          ${isEdit ? `<input type="hidden" name="id" value={item()!.id} />` : ''}
${inputs}
          <Show when={submission.error}>
            <p class="text-sm text-destructive">{String(submission.error)}</p>
          </Show>
          <button type="submit" class={buttonVariants()}>{t('${P}Page.save')}</button>
        </form>
      </Show>
    </>
  );
}
`;
}

function generateEntity(e, out) {
  const dir = path.join(out, 'src');
  const name = e.name;
  const P = pascal(name);

  // 1. zigmodu REST bridge (once)
  const apiLib = path.join(dir, 'libs', 'zmoduApi.ts');
  if (!fs.existsSync(apiLib)) {
    fs.mkdirSync(path.dirname(apiLib), { recursive: true });
    fs.writeFileSync(apiLib, ZMODU_API_TS);
  }
  // 2. business module (server actions calling zigmodu)
  const bizDir = path.join(dir, 'business', name);
  fs.mkdirSync(bizDir, { recursive: true });
  fs.writeFileSync(path.join(bizDir, 'index.ts'), actionsTpl(e));
  // 3. dashboard routes
  const routeDir = path.join(dir, 'routes', 'dashboard', name);
  fs.mkdirSync(routeDir, { recursive: true });
  fs.writeFileSync(path.join(routeDir, 'index.tsx'), listPageTpl(e));
  fs.writeFileSync(path.join(routeDir, 'new.tsx'), formPageTpl(e, 'new'));
  fs.writeFileSync(path.join(routeDir, '[id].tsx'), formPageTpl(e, 'edit'));

  // 4. nav item
  const dashPath = path.join(dir, 'routes', 'dashboard.tsx');
  if (fs.existsSync(dashPath)) {
    let dash = fs.readFileSync(dashPath, 'utf8');
    const marker = `// zsaas:nav:${name}`;
    if (!dash.includes(marker)) {
      const navLine = `              { href: '/dashboard/${name}', label: t('DashboardLayout.${name}') as string }, // ${marker}\n`;
      const anchor = `{ href: '/dashboard/members'`;
      const idx = dash.indexOf(anchor);
      if (idx >= 0) {
        const lineEnd = dash.indexOf('\n', idx);
        dash = dash.slice(0, lineEnd + 1) + navLine + dash.slice(lineEnd + 1);
        fs.writeFileSync(dashPath, dash);
      } else {
        console.warn(`[zsaas] could not patch nav in ${dashPath}; add the item manually`);
      }
    }
  }

  // 5. i18n keys
  for (const loc of ['en', 'zh']) {
    const locPath = path.join(dir, 'locales', `${loc}.json`);
    if (!fs.existsSync(locPath)) continue;
    const json = JSON.parse(fs.readFileSync(locPath, 'utf8'));
    json[`${P}Page`] = {
      title_bar: e.label,
      title_bar_description: e.description ?? '',
      list: `${e.label} list`,
      create: 'Create',
      edit: 'Edit',
      delete: 'Delete',
      save: 'Save',
      empty: 'No records yet.',
      create_title: `New ${e.label}`,
      edit_title: `Edit ${e.label}`,
      ...Object.fromEntries(e.fields.map(f => [`f_${f.name}`, f.label ?? f.name])),
    };
    if (json.DashboardLayout) json.DashboardLayout[e.name] = e.label;
    fs.writeFileSync(locPath, JSON.stringify(json, null, 2) + '\n');
  }

  console.log(`[zsaas] generated ${name} -> ${dir}`);
}

for (const e of model.entities) {
  generateEntity(e, TARGET);
}
console.log('[zsaas] done');
